CREATE OR REPLACE TABLE HIGH_USAGE_ALERT_TABLE (
    customerId STRING,
    unitsConsumed NUMBER,
    alert_time TIMESTAMP
);

CREATE OR REPLACE TASK HIGH_USAGE_TASK
WAREHOUSE = ENERGY_WH
SCHEDULE = '1 MINUTE'
AS
INSERT INTO HIGH_USAGE_ALERT_TABLE
SELECT
    customerId,
    unitsConsumed,
    CURRENT_TIMESTAMP()
FROM RAW_LAYER.METER_READING_STREAM
WHERE unitsConsumed > 800;

ALTER TASK HIGH_USAGE_TASK RESUME;

CREATE OR REPLACE DYNAMIC TABLE DT_DAILY_CONSUMPTION
TARGET_LAG = '1 minute'
WAREHOUSE = ENERGY_WH
AS
SELECT
    customerId,
    SUM(unitsConsumed) AS total_units
FROM RAW_LAYER.METER_READING_RAW
GROUP BY customerId;

SELECT *
FROM DT_DAILY_CONSUMPTION;
