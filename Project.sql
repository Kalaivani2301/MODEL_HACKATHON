USE SCHEMA ANALYTICS_LAYER;

CREATE OR REPLACE TABLE DIM_CUSTOMER AS
SELECT DISTINCT
    customerId,
    customerName,
    meterNumber,
    city,
    customerType,
    customerStatus
FROM RAW_LAYER.CUSTOMER_RAW;

CREATE OR REPLACE TABLE DIM_POWER_STATION AS
SELECT DISTINCT
    stationId,
    stationName,
    location,
    operationalStatus
FROM RAW_LAYER.POWER_STATION_RAW;

CREATE OR REPLACE TABLE FACT_BILLING AS
SELECT
    transactionId,
    B.customerId,
    billAmount,
    dueDate,
    paymentStatus,
    customerType,
    city
FROM RAW_LAYER.BILLING_TRANSACTION_RAW B
JOIN DIM_CUSTOMER C
ON B.customerId = C.customerId;

CREATE OR REPLACE TABLE FACT_METER_READING AS
SELECT
    readingId,
    M.customerId,
    unitsConsumed,
    readingDate,
    readingStatus,
    city,
    customerType
FROM RAW_LAYER.METER_READING_RAW M
JOIN DIM_CUSTOMER C
ON M.customerId = C.customerId;

USE SCHEMA ANALYTICS_LAYER;

CREATE OR REPLACE VIEW VW_BILLING_SUMMARY AS
SELECT
    customerId,
    city,
    customerType,
    SUM(billAmount) AS total_bill,
    COUNT(transactionId) AS total_transactions
FROM FACT_BILLING
GROUP BY customerId, city, customerType;

CREATE OR REPLACE VIEW VW_CONSUMPTION_SUMMARY AS
SELECT
    customerId,
    city,
    customerType,
    AVG(unitsConsumed) AS avg_consumption,
    MAX(unitsConsumed) AS max_consumption,
    SUM(unitsConsumed) AS total_consumption
FROM FACT_METER_READING
GROUP BY customerId, city, customerType;

CREATE OR REPLACE VIEW VW_HIGH_USAGE_ALERTS AS
SELECT
    customerId,
    unitsConsumed,
    readingDate,
    CASE
        WHEN unitsConsumed > 800 THEN 'HIGH_USAGE'
        ELSE 'NORMAL'
    END AS usage_status
FROM FACT_METER_READING;

CREATE OR REPLACE VIEW VW_REVENUE_ANALYSIS AS
SELECT
    city,
    customerType,
    SUM(billAmount) AS revenue,
    AVG(billAmount) AS avg_bill
FROM FACT_BILLING
GROUP BY city, customerType;

CREATE OR REPLACE VIEW MV_CITY_REVENUE AS
SELECT
    city,
    SUM(billAmount) AS total_revenue
FROM FACT_BILLING
GROUP BY city;

CREATE OR REPLACE VIEW MV_CONSUMPTION_TREND AS
SELECT
    customerType,
    AVG(unitsConsumed) AS avg_units
FROM FACT_METER_READING
GROUP BY customerType;

